import assert from 'node:assert/strict';
import fs from 'node:fs';
import { observe } from '../lib/game/ai';
import { newGame } from '../lib/game/engine';
import { actionKey, validAiAction } from './ai-gateway';
import { decideSearch, decideSearchWithBaseline } from './search-ai';
import { decideModelSearch } from './model-search';
import { validateModel, selectNeuralAction } from './neural-policy';
import { buildAiRequest } from './ai-gateway';
import { modelSearchDuel } from './model-search-benchmark';
const model=validateModel(JSON.parse(fs.readFileSync(process.argv[2],'utf8')));
const state=newGame(7001),o=observe(state,state.turn);
assert.deepEqual(decideSearchWithBaseline(o,decideSearch(o).baseline),decideSearch(o));
assert.throws(()=>decideSearchWithBaseline(o,{cards:['bad']}));
const result=decideModelSearch(o,model);
assert.equal(result.searched,false);
assert.equal(actionKey(result.action),actionKey(selectNeuralAction(model,buildAiRequest(o,'play','fixture'))));
assert.ok(validAiAction(o,result.action));
const game=modelSearchDuel(22839,0,model);assert.ok(game.upgrade>=1&&game.upgrade<=3);
console.log(JSON.stringify({passed:true,steps:game.steps,searched:game.searched,changed:game.changed}));
