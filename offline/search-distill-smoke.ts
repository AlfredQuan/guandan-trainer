import assert from 'node:assert/strict';
import { observe } from '../lib/game/ai';
import { newGame } from '../lib/game/engine';
import { decideSearch } from './search-ai';
import { distillRow, generateDistillDeal } from './search-distill';
import { actionKey, buildAiRequest } from './ai-gateway';
const state=newGame(9011),o=observe(state,state.turn),decision=decideSearch(o);
const row=distillRow(o,decision,'fixture');
assert.equal(actionKey(row.actions[row.teacher]),actionKey(decision.action));
assert.equal(actionKey(row.actions[row.baseline]),actionKey(decision.baseline));
assert.ok(row.features.every(x=>x.length===155&&x.every(Number.isFinite)));
assert.ok(!('seed' in row));
assert.throws(()=>distillRow(o,{...decision,action:{cards:['not-in-hand']}},'bad'));
const alternative=buildAiRequest(o,'play','alternate').actions.find(a=>actionKey(a)!==actionKey(decision.baseline))!;
assert.ok(alternative);
const changed=distillRow(o,{...decision,action:alternative,changed:true,searched:true,gain:0.5},'changed');
assert.notEqual(changed.teacher,changed.baseline);
assert.equal(actionKey(changed.actions[changed.teacher]),actionKey(alternative));
const reversed={...state,players:state.players.map(p=>p.seat===o.seat?p:{...p,hand:[...p.hand].reverse()})};
assert.deepEqual(distillRow(observe(reversed,o.seat),decision,'fixture'),row,'opponent hand order must not leak into features');
const deal=generateDistillDeal(7001,undefined,0);
assert.ok(deal.rows.length>0);assert.equal(deal.finished,true);
assert.equal(deal.stats.missingTargets,0);
assert.ok(deal.rows.every(r=>r.teacher>=0&&r.baseline>=0&&!('actions' in r)));
assert.deepEqual([...new Set(deal.rows.map(r=>r.seat))].sort(),[0,1,2,3]);
console.log(JSON.stringify({ok:true,rows:deal.rows.length,stats:deal.stats}));
